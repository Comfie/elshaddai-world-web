#!/usr/bin/env node
/**
 * Scans public/images for photography and writes lib/image-manifest.generated.ts.
 * The site only renders a photo for a slot when its file is listed here, so
 * missing files never cause 404s — the designed placeholder shows instead.
 *
 * Runs automatically before `dev` and `build`. To add a photo: drop it in
 * public/images/<folder>/<name>.jpg (see public/images/README.md) and redeploy.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const imagesDir = join(root, 'public', 'images');
const exts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);

function walk(dir) {
  let out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out = out.concat(walk(full));
    else if (exts.has(name.slice(name.lastIndexOf('.')).toLowerCase())) out.push(relative(imagesDir, full).split('\\').join('/'));
  }
  return out;
}

let files = [];
try {
  files = walk(imagesDir).sort();
} catch {
  /* no images directory yet */
}

const body = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit.
export const AVAILABLE_IMAGES: string[] = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(join(root, 'lib', 'image-manifest.generated.ts'), body);
console.log(`[images] ${files.length} photo(s) found in public/images`);
